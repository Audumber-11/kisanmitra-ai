export function detectFarmingTopic(query: string, language: Language): string {
  const q = query.toLowerCase().trim();
  if (!q) return "default";

  // Check each topic's keywords
  for (const [topic, keywords] of Object.entries(TOPIC_KEYWORDS)) {
    const langKeywords = keywords[language] || [];
    for (const keyword of langKeywords) {
      if (q.includes(keyword.toLowerCase())) {
        return topic;
      }
    }
  }

  return "default";
}

// ============================================================
// HELPER: Get KB answer for a query (with topic detection)
// ============================================================

export function getKnowledgeAnswer(query: string, language: Language): string {
  const langKB = FARMING_KNOWLEDGE_BASE[language] || FARMING_KNOWLEDGE_BASE.hindi;
  const topic = detectFarmingTopic(query, language);
  return langKB[topic] || langKB.default;
}

